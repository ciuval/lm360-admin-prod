-- Il trigger è proprietario della sola creazione di match da 2 like distinti.
-- Nessuna sessione client può scrivere match_scores.
create or replace function public.lm360_lab_match_after_like()
returns trigger
language plpgsql
security definer
set search_path = ''
as $fn$
begin
  if new.user_id <> auth.uid() or new.user_from <> new.user_id then
    raise exception 'LIKE_OWNER_MISMATCH';
  end if;

  if exists (
    select 1 from public.likes l
     where l.user_id = new.user_to and l.user_to = new.user_id
  ) then
    insert into public.match_scores (user_a,user_b,score,matched_at)
    values (least(new.user_id,new.user_to),
            greatest(new.user_id,new.user_to),100,now())
    on conflict (user_a,user_b) do update
       set score = 100, matched_at = coalesce(public.match_scores.matched_at,now()),
           updated_at = now();
  end if;
  return new;
end;
$fn$;

revoke all on function public.lm360_lab_match_after_like() from public,anon,authenticated;
create trigger lm360_lab_reciprocal_after_like
 after insert on public.likes for each row
 execute function public.lm360_lab_match_after_like();

-- Scoperta consensuale: sei campi e nessun SELECT sulle righe altrui.
create or replace function public.lm360_get_public_profiles(p_profile_id uuid default null)
returns table (
 id uuid, nome text, bio text, interessi text, foto_url text, premium boolean
)
language sql stable security definer
set search_path = ''
as $rpc$
 select p.id,p.nome,p.bio,p.interessi,
        coalesce(nullif(btrim(p.foto_url),''),
                 nullif(btrim(p.avatar_url),''),
                 gf.foto_url) as foto_url,
        (p.premium is true or p.ruolo in ('premium','super')
                  or p.premium_fine > now()) as premium
 from public.profili p
 left join lateral (
   select f.foto_url
   from public.profili_foto f
   where f.profilo_id=p.id and nullif(btrim(f.foto_url),'') is not null
   order by f.is_primary desc,f.ordine asc
   limit 1
 ) gf on true
 where auth.uid() is not null
   and p.profilo_pubblico is true
   and p.status_account='attivo'
   and p.id <> auth.uid()
   and (p_profile_id is null or p.id=p_profile_id)
   and char_length(btrim(coalesce(p.nome,'')))>=2
   and char_length(btrim(coalesce(p.bio,'')))>=20
   and char_length(btrim(coalesce(p.interessi,'')))>=1
   and coalesce(nullif(btrim(p.foto_url),''),
                nullif(btrim(p.avatar_url),''),
                gf.foto_url) is not null
 order by p.nome,p.id limit 50;
$rpc$;

revoke all on function public.lm360_get_public_profiles(uuid) from public,anon;
grant execute on function public.lm360_get_public_profiles(uuid) to authenticated;

