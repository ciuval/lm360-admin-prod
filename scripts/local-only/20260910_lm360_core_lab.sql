create table public.profili (
  id uuid primary key references auth.users(id) on delete cascade,
  nome text,
  email text,
  bio text,
  interessi text,
  foto_url text,
  avatar_url text,
  ruolo text not null default 'utente',
  premium boolean not null default false,
  premium_start timestamptz,
  premium_fine timestamptz,
  tipo_abbonamento text,
  profilo_pubblico boolean not null default false,
  status_account text not null default 'attivo',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.profili_foto (
  id uuid primary key default gen_random_uuid(),
  profilo_id uuid not null references public.profili(id) on delete cascade,
  foto_url text not null,
  ordine integer not null default 0 check (ordine between 0 and 4),
  is_primary boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.likes (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  user_from uuid not null references auth.users(id) on delete cascade,
  user_to uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  constraint likes_sender_consistent check (user_id = user_from),
  constraint likes_distinct_users check (user_from <> user_to),
  constraint likes_directed_unique unique (user_id,user_to)
);

create table public.match_scores (
  user_a uuid not null references auth.users(id) on delete cascade,
  user_b uuid not null references auth.users(id) on delete cascade,
  score integer not null default 0 check (score in (0,100)),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  matched_at timestamptz,
  constraint match_scores_pk primary key (user_a,user_b),
  constraint match_pair_chk check (user_a < user_b)
);

create table public.messaggi (
  id integer generated by default as identity primary key,
  mittente_id uuid not null references auth.users(id) on delete cascade,
  destinatario_id uuid not null references auth.users(id) on delete cascade,
  testo text,
  letto boolean not null default false,
  inviato_il timestamp without time zone not null default now(),
  constraint messaggi_distinct_users check (mittente_id <> destinatario_id)
);

